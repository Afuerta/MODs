/**
 * In-game tests, run headless with {@code gradle runGameTestServer} (and on every pull request in
 * CI). Each test runs inside the empty 9x9x9 structure {@code starfall:empty}, which is generated by
 * the {@code generateTestStructures} Gradle task.
 *
 * <p>Add a test here for every new feature.
 */
@GameTestHolder(Starfall.MOD_ID)
@PrefixGameTestTemplate(false)
public final class StarfallGameTests {
    private static final String EMPTY = "empty";

    private static final List<String> RECIPES = List.of(
            "stardust", "starsteel_ingot", "starsteel_block", "starsteel_ingot_from_block", "starstone_bricks",
            "star_lantern", "wishing_star", "starsteel_sword", "starsteel_pickaxe", "starsteel_axe",
            "starsteel_shovel", "starsteel_hoe", "star_shard_from_smelting", "star_shard_from_blasting");

    @GameTest(template = EMPTY)
    public static void dataFilesLoad(GameTestHelper helper) {
        MinecraftServer server = helper.getLevel().getServer();
        for (String recipe : RECIPES) {
            helper.assertTrue(server.getRecipeManager().byKey(Starfall.id(recipe)).isPresent(),
                    "Missing recipe starfall:" + recipe);
        }
        for (Block block : List.of(ModBlocks.STARSTONE.get(), ModBlocks.STARSTONE_BRICKS.get(),
                ModBlocks.STARSTONE_ORE.get(), ModBlocks.FALLEN_STAR.get(), ModBlocks.STARSTEEL_BLOCK.get(),
                ModBlocks.STAR_LANTERN.get())) {
            LootTable table = server.reloadableRegistries().getLootTable(block.getLootTable());
            helper.assertTrue(table != LootTable.EMPTY, "Missing loot table for " + block);
            helper.assertTrue(block.defaultBlockState().is(BlockTags.MINEABLE_WITH_PICKAXE),
                    block + " should be mineable with a pickaxe");
        }
        helper.assertTrue(new ItemStack(ModItems.STARSTEEL_PICKAXE.get()).is(ItemTags.PICKAXES),
                "Starsteel pickaxe should be in #minecraft:pickaxes");
        helper.assertTrue(new ItemStack(ModItems.STARSTEEL_SWORD.get()).is(ModTags.Items.STARLIT_TOOLS),
                "Starsteel sword should be in #starfall:starlit_tools");
        helper.succeed();
    }

    @GameTest(template = EMPTY)
    public static void impactCarvesCraterWithFallenStar(GameTestHelper helper) {
        for (int x = 0; x < 9; x++) {
            for (int z = 0; z < 9; z++) {
                for (int y = 1; y <= 3; y++) {
                    helper.setBlock(new BlockPos(x, y, z), Blocks.STONE);
                }
            }
        }
        BlockPos ground = helper.absolutePos(new BlockPos(4, 3, 4));
        BlockPos star = StarImpact.impact(helper.getLevel(), ground, 2);

        helper.assertTrue(helper.getLevel().getBlockState(star).is(ModBlocks.FALLEN_STAR.get()),
                "Impact should leave a fallen star");
        helper.assertTrue(star.getY() < ground.getY(), "The fallen star should sit inside a crater");
        helper.assertTrue(helper.getLevel().getBlockState(ground).isAir(), "The crater should be hollowed out");
        boolean lined = false;
        for (BlockPos pos : BlockPos.betweenClosed(ground.offset(-2, -3, -2), ground.offset(2, 0, 2))) {
            Block block = helper.getLevel().getBlockState(pos).getBlock();
            if (block == ModBlocks.STARSTONE.get() || block == ModBlocks.STARSTONE_ORE.get()) {
                lined = true;
                break;
            }
        }
        helper.assertTrue(lined, "The crater should be lined with starstone");
        helper.succeed();
    }

    @GameTest(template = EMPTY)
    public static void impactHurtsNearbyMobs(GameTestHelper helper) {
        for (int x = 2; x <= 6; x++) {
            for (int z = 2; z <= 6; z++) {
                helper.setBlock(new BlockPos(x, 1, z), Blocks.STONE);
            }
        }
        Pig pig = helper.spawn(EntityType.PIG, new BlockPos(5, 2, 4));
        float before = pig.getHealth();
        StarImpact.impact(helper.getLevel(), helper.absolutePos(new BlockPos(4, 1, 4)), 0);
        helper.assertTrue(pig.getHealth() < before || !pig.isAlive(), "The impact shockwave should hurt the pig");
        helper.succeed();
    }

    @GameTest(template = EMPTY)
    public static void stardustGrowsCrops(GameTestHelper helper) {
        BlockPos crop = new BlockPos(4, 2, 4);
        helper.setBlock(crop.below(), Blocks.FARMLAND);
        helper.setBlock(crop, Blocks.WHEAT);
        ItemStack stack = new ItemStack(ModItems.STARDUST.get(), 3);

        boolean used = StardustItem.applyStardust(stack, helper.getLevel(), helper.absolutePos(crop));

        helper.assertTrue(used, "Stardust should work on wheat");
        helper.assertTrue(helper.getBlockState(crop).getValue(CropBlock.AGE) > 0, "Wheat should have grown");
        helper.assertTrue(stack.getCount() == 2, "Using stardust should consume one");
        helper.succeed();
    }

    @GameTest(template = EMPTY)
    public static void wishingStarGrantsAnEffect(GameTestHelper helper) {
        helper.setBlock(new BlockPos(4, 1, 4), Blocks.STONE);
        Pig pig = helper.spawn(EntityType.PIG, new BlockPos(4, 2, 4));
        WishingStarItem.grantWish(pig, helper.getLevel().getRandom());
        helper.assertTrue(!pig.getActiveEffects().isEmpty(), "A wish should grant an effect");
        helper.succeed();
    }

    @GameTest(template = EMPTY)
    public static void compassDirections(GameTestHelper helper) {
        assertDirection(helper, 0, -10, "north");
        assertDirection(helper, 10, 0, "east");
        assertDirection(helper, 0, 10, "south");
        assertDirection(helper, -10, 0, "west");
        assertDirection(helper, 10, -10, "north_east");
        assertDirection(helper, -10, 10, "south_west");
        helper.succeed();
    }

    private static void assertDirection(GameTestHelper helper, double dx, double dz, String expected) {
        String key = ((TranslatableContents) StarfallUtil.direction(dx, dz).getContents()).getKey();
        helper.assertTrue(key.equals("direction.starfall." + expected),
                "Offset (" + dx + ", " + dz + ") should be " + expected + " but was " + key);
    }

    private StarfallGameTests() {
    }
}
